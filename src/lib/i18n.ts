const DICT: Record<Lang, Record<TKey, string>> = { en, th };

let lang: Lang | null = null;
const listeners = new Set<() => void>();

function current(): Lang {
  if (lang) return lang;
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "en" || saved === "th") lang = saved;
  } catch { /* storage blocked */ }
  lang ??= navigator.language?.toLowerCase().startsWith("th") ? "th" : "en";
  document.documentElement.lang = lang;
  return lang;
}

export function setLang(next: Lang) {
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* storage blocked */ }
  document.documentElement.lang = next;
  listeners.forEach((l) => l());
}

function subscribe(l: () => void) {
  listeners.add(l);
  const onStorage = (e: StorageEvent) => {
    if (e.key === KEY && (e.newValue === "en" || e.newValue === "th")) setLang(e.newValue);
  };
  window.addEventListener("storage", onStorage);
  return () => {
    listeners.delete(l);
    window.removeEventListener("storage", onStorage);
  };
}

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, current, () => "en");
}

export type T = (key: TKey, vars?: Record<string, string | number>) => string;

export function translate(l: Lang, key: TKey, vars?: Record<string, string | number>) {
  const s = DICT[l][key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

export function useT(): T {
  const l = useLang();
  return useCallback((key, vars) => translate(l, key, vars), [l]);
}

/** Header button that flips the interface language. */
export function useLangToggle() {
  const l = useLang();
  return { lang: l, toggle: () => setLang(l === "en" ? "th" : "en") };
}
